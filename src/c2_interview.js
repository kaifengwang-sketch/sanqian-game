  // ---- 投简历 → 面试邀约 ----
  const WEIGHTS = {
    wide: () => ({ media: 3, edu: 3, admin: 2, sales: 1.5, ad: 1, live: 1.5, scam: 1.5, bigtech: 0.1 }),
    narrow: (s) => ({ ad: 3, media: 2, sales: 2, admin: 2, bigtech: s.stats.skill < 30 ? 0.2 : 0.5 + (s.stats.skill - 30) / 12 }),
    fair: () => ({ media: 2, edu: 2, admin: 1.5, sales: 2, ad: 1, live: 1, scam: 0.5 }),
  };
  function makeInvite(s, track, at) {
    const T = TRACKS[track];
    const company = say(s, T.companies);
    let level = 0, lo = T.start[0], hi = T.start[1];
    const pv = s.prev;
    // 有工作经验以后，邀约按上一份工作定级定薪
    if (pv && !T.trap) {
      if (pv.track === track) {
        level = pv.level;
        lo = r100(Math.max(T.start[0], pv.pay * 0.95));
        hi = r100(pv.pay * 1.25);
      } else {
        level = clamp(pv.level - 1, 0, T.titles.length - 1);
        lo = r100(Math.max(T.start[0], T.pay[level] * 0.9));
        hi = r100(Math.max(T.start[1], T.pay[level] * 1.15));
      }
    }
    return { uid: nextId(s), track, company, level, lo, hi, at };
  }
  function addInvites(s, n, mode) {
    const w = WEIGHTS[mode](s);
    const list = Object.keys(w).map((k) => ({ k, weight: w[k] }));
    for (let i = 0; i < n; i++) s.invites.push(makeInvite(s, pickWeighted(s, list).k, s.turn + 1));
  }
  // 面试里的随机都在排进队列时定好，场景渲染时不再掷骰子
  function enqueueInterview(s, inv) {
    if (inv.track === 'scam' || inv.track === 'live') {
      s.queue.push({ id: inv.track, p: { inv } });
      return;
    }
    const T = TRACKS[inv.track];
    const nT = inv.track === 'bigtech' ? 2 : 1;
    const tq = shuffle(s, QS[inv.track].map((_, i) => i)).slice(0, nT).map((i) => ({ k: inv.track, i }));
    const qs = [...tq, { k: 'general', i: rint(s, 0, QS.general.length - 1) }];
    const ord = qs.map((q) => shuffle(s, QS[q.k][q.i].o.map((_, j) => j)));
    s.queue.push({ id: 'hr', p: { inv, good: chance(s, T.goodHR), v: rint(s, 0, 99), qs, ord, i: 0, sc: 0, react: '', gb: 0 } });
  }
  function pushOffer(s, o) { s.offers.push({ uid: nextId(s), ...o }); }

  // 谈薪结果：答题得分 + 专业和表达 + 状态 + 一点运气，减去岗位门槛
  function settle(s, p, kind, ask, mid) {
    const inv = p.inv, T = TRACKS[inv.track];
    let score = p.sc / (2 * p.qs.length) + (s.stats.skill - 30) / 180 + (s.stats.talk - 30) / 180 + p.gb + (rnd(s) - 0.5) * 0.16;
    if (s.stats.energy < 30) score -= 0.1;
    if (s.stats.mood < 25) score -= 0.05;
    const q = score - T.diff;
    let pay = 0;
    if (kind === 'hi') { if (q >= 0.18) pay = ask; else if (q >= 0.02 && chance(s, 0.5)) pay = mid; }
    else if (kind === 'mid') { if (q >= 0.08) pay = ask; else if (q >= -0.06) pay = inv.lo; }
    else if (q >= -0.16) pay = inv.lo;
    if (!pay) {
      if (q > -0.22 && chance(s, 0.2)) s.later.push({ at: s.turn + rint(s, 1, 2), id: 'callback', p: { inv } });
      log(s, `面试${inv.company}：回去等通知`);
      return '“今天就先到这儿，你回去等通知吧。”\n\n你知道，这句话的意思一般就是凉了。';
    }
    const pw = T.comm ? '底薪' : '月薪';
    pushOffer(s, { track: inv.track, company: inv.company, level: inv.level, pay, exp: s.turn + 1 });
    log(s, `拿到${inv.company}的 offer，${pw} ${money(pay)}`);
    let text;
    if (pay === ask && kind === 'hi') text = 'HR 愣了一下，低头算了算：“可以，就按你说的。”';
    else if (pay === ask) text = 'HR 点点头：“这个数没问题。”';
    else if (kind === 'hi') text = `HR 笑了：“这个数有点高。我们最多给到 ${money(pay)}，你考虑一下？”`;
    else if (kind === 'mid') text = `HR 说：“应届生嘛，先按 ${money(pay)} 来，转正以后再看。”`;
    else text = 'HR 爽快地答应了。你有点后悔，是不是报低了。';
    return `${text}\n\n${inv.company}给了 offer：${T.titles[inv.level]}，${pw} ${money(pay)}。两周内有效，在下面的 offer 栏里决定接不接。`;
  }
